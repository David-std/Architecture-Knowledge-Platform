function parsePositiveInteger(value: string | undefined, name: string): number {
  const parsed = Number(value);
  if (!Number.isInteger(parsed) || parsed <= 0) {
    throw new Error(`${name} must be a positive integer`);
  }
  return parsed;
}

function parseTargets(value: string | undefined): number[] {
  const raw = value ?? "1000,10000,50000,100000";
  const targets = raw
    .split(",")
    .map((item) => parsePositiveInteger(item.trim(), "target"));
  if (targets.length === 0) throw new Error("at least one target is required");
  if (targets.some((target) => target > 1_000_000)) {
    throw new Error("targets above 1,000,000 are refused by the harness");
  }
  for (let index = 1; index < targets.length; index += 1) {
    const current = targets[index];
    const previous = targets[index - 1];
    if (
      current === undefined ||
      previous === undefined ||
      current <= previous
    ) {
      throw new Error("targets must be strictly ascending");
    }
  }
  return targets;
}

function asNumber(value: Numeric | null | undefined): number {
  const parsed = Number(value ?? 0);
  if (!Number.isFinite(parsed))
    throw new Error(`non-numeric database value: ${value}`);
  return parsed;
}

function roundMs(value: number): number {
  return Math.round(value * 1000) / 1000;
}

function roundBytes(value: number): number {
  return Math.max(0, Math.round(value));
}

function snapshotMemory(): MemorySnapshot {
  const memory = process.memoryUsage();
  return {
    rssBytes: memory.rss,
    heapUsedBytes: memory.heapUsed,
    heapTotalBytes: memory.heapTotal,
    externalBytes: memory.external,
  };
}

function subtractMemory(
  after: MemorySnapshot,
  before: MemorySnapshot,
): {
  rssBytes: number;
  heapUsedBytes: number;
} {
  return {
    rssBytes: after.rssBytes - before.rssBytes,
    heapUsedBytes: after.heapUsedBytes - before.heapUsedBytes,
  };
}

function subtractStorage(
  after: StorageSnapshot,
  before: StorageSnapshot,
): StorageSnapshot {
  return {
    databaseBytes: after.databaseBytes - before.databaseBytes,
    documentsTableBytes: after.documentsTableBytes - before.documentsTableBytes,
    unitsTableBytes: after.unitsTableBytes - before.unitsTableBytes,
    relationsTableBytes: after.relationsTableBytes - before.relationsTableBytes,
    embeddingsTableBytes:
      after.embeddingsTableBytes - before.embeddingsTableBytes,
  };
}

function summarize(samples: number[]): Stats {
  if (samples.length === 0)
    throw new Error("cannot summarize an empty sample set");
  const sorted = [...samples].sort((left, right) => left - right);
  const percentile = (fraction: number): number => {
    const index = Math.min(
      sorted.length - 1,
      Math.max(0, Math.ceil(sorted.length * fraction) - 1),
    );
    const value = sorted[index];
    if (value === undefined)
      throw new Error("percentile index outside sample set");
    return value;
  };
  const minimum = sorted[0];
  const maximum = sorted[sorted.length - 1];
  if (minimum === undefined || maximum === undefined) {
    throw new Error("cannot summarize an empty sample set");
  }
  return {
    samples: samples.length,
    minMs: roundMs(minimum),
    p50Ms: roundMs(percentile(0.5)),
    p95Ms: roundMs(percentile(0.95)),
    maxMs: roundMs(maximum),
    meanMs: roundMs(
      samples.reduce((total, sample) => total + sample, 0) / samples.length,
    ),
  };
}

function errorMessage(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}

async function timedQuery<T extends pg.QueryResultRow = pg.QueryResultRow>(
  text: string,
  values: unknown[] = [],
): Promise<{ result: pg.QueryResult<T>; elapsedMs: number }> {
  const started = performance.now();
  const result = await client.query<T>(text, values);
  return { result, elapsedMs: performance.now() - started };
}

async function databaseInfo(): Promise<{ version: string; name: string }> {
  const result = await client.query<{ version: string; name: string }>(
    "select current_setting('server_version') as version, current_database() as name",
  );
  const row = result.rows[0];
  if (!row) throw new Error("PostgreSQL did not return server information");
  return { version: row.version, name: row.name };
}

async function storageSnapshot(): Promise<StorageSnapshot> {
  const result = await client.query<{
    database_bytes: Numeric;
    documents_table_bytes: Numeric;
    units_table_bytes: Numeric;
    relations_table_bytes: Numeric;
    embeddings_table_bytes: Numeric;
  }>(`
    select
      pg_database_size(current_database())::bigint as database_bytes,
      pg_total_relation_size('public.knowledge_documents'::regclass)::bigint as documents_table_bytes,
      pg_total_relation_size('public.knowledge_units'::regclass)::bigint as units_table_bytes,
      pg_total_relation_size('public.knowledge_relations'::regclass)::bigint as relations_table_bytes,
      pg_total_relation_size('public.unit_embeddings'::regclass)::bigint as embeddings_table_bytes
  `);
  const row = result.rows[0];
  if (!row) throw new Error("PostgreSQL did not return storage information");
  return {
    databaseBytes: asNumber(row.database_bytes),
    documentsTableBytes: asNumber(row.documents_table_bytes),
    unitsTableBytes: asNumber(row.units_table_bytes),
    relationsTableBytes: asNumber(row.relations_table_bytes),
    embeddingsTableBytes: asNumber(row.embeddings_table_bytes),
  };
}

async function createFixture(seed: string): Promise<FixtureIds> {
  const runId = randomUUID();
  const compactRunId = runId.replaceAll("-", "").slice(0, 12);
  const slug = `akp-scale-${compactRunId}`;
  const externalPrefix = `synthetic-${seed}-${compactRunId}-`;
  const organization = await client.query<{ id: string }>(
    "insert into organizations(slug,name) values ($1,$2) returning id",
    [slug, `Synthetic scale benchmark ${runId}`],
  );
  const organizationId = organization.rows[0]?.id;
  if (!organizationId)
    throw new Error("failed to create synthetic organization");

  const space = await client.query<{ id: string }>(
    `insert into spaces(organization_id,slug,name,visibility,knowledge_repo_path)
     values ($1,$2,$3,'PRIVATE',$4) returning id`,
    [organizationId, slug, `Synthetic scale benchmark ${runId}`, ""],
  );
  const spaceId = space.rows[0]?.id;
  if (!spaceId) throw new Error("failed to create synthetic space");

  const canonicalPath = `synthetic://akp-scale/${runId}`;
  const vault = await client.query<{ id: string }>(
    `insert into vaults(
       space_id,canonical_path,name,read_only,vault_key,local_path,
       content_roots,source_roots,schema_profile,eval_pack,retrieval_config,
       permissions,enabled,visibility
     ) values ($1,$2,$3,true,$4,$2,array['.']::text[],'{}'::text[],'{}'::jsonb,
       '{"name":"synthetic-scale","version":"1"}'::jsonb,'{}'::jsonb,
       '{}'::jsonb,true,'PRIVATE') returning id`,
    [
      spaceId,
      canonicalPath,
      `Synthetic scale benchmark ${runId}`,
      `akp-scale-${compactRunId}`,
    ],
  );
  const vaultId = vault.rows[0]?.id;
  if (!vaultId) throw new Error("failed to create synthetic vault");
  const generation = await client.query<{ id: string }>(
    `insert into embedding_generations(
       space_id,vault_id,provider,model,model_revision,dimensions,normalization,
       configuration_version,corpus_revision,status,activated_at
     ) values ($1,$2,'synthetic','synthetic-64','v1',64,'NONE','load-scale-v1',
       'synthetic-v1','ACTIVE',now()) returning id`,
    [spaceId, vaultId],
  );
  const embeddingGenerationId = generation.rows[0]?.id;
  if (!embeddingGenerationId) {
    throw new Error("failed to create synthetic embedding generation");
  }
  return {
    organizationId,
    spaceId,
    vaultId,
    embeddingGenerationId,
    externalPrefix,
    runId,
  };
}

async function fixtureCounts(fixture: FixtureIds): Promise<RowCounts> {
  const result = await client.query<{
    documents: Numeric;
    units: Numeric;
    relations: Numeric;
    embeddings: Numeric;
  }>(
    `select
       (select count(*) from knowledge_documents where space_id=$1 and vault_id=$2)::bigint as documents,
       (select count(*) from knowledge_units where space_id=$1 and vault_id=$2)::bigint as units,
       (select count(*)
          from knowledge_relations r
          join knowledge_documents f on f.id=r.from_document_id
          join knowledge_documents t on t.id=r.to_document_id
         where r.space_id=$1 and f.vault_id=$2 and t.vault_id=$2)::bigint as relations,
       (select count(*)
          from unit_embeddings e
          join knowledge_units u on u.id=e.unit_id
         where u.space_id=$1 and u.vault_id=$2 and e.generation_id=$3)::bigint as embeddings`,
    [fixture.spaceId, fixture.vaultId, fixture.embeddingGenerationId],
  );
  const row = result.rows[0];
  if (!row) throw new Error("PostgreSQL did not return fixture counts");
  return {
    documents: asNumber(row.documents),
    units: asNumber(row.units),
    relations: asNumber(row.relations),
    embeddings: asNumber(row.embeddings),
  };
}

async function insertDocuments(
  fixture: FixtureIds,
  start: number,
  end: number,
): Promise<number> {
  if (start > end) return 0;
  const { elapsedMs } = await timedQuery(
    `insert into knowledge_documents(
       space_id,vault_id,external_id,path,title,type,lifecycle,trust_tier,
       current_revision,body_cache,frontmatter,layer,content_hash,token_estimate,raw_links
     )
     select
       $1,$2,$3 || i::text,
       format('synthetic/%s.md',i),
       format('Synthetic architecture scale document %s',i),
       'synthetic-document','ACTIVE','VERIFIED','synthetic-v1',
       format('Synthetic architecture benchmark document %s. This deterministic fixture
               contains the shared architecture search token and seed %s.',i,$4::text),
       jsonb_build_object('synthetic',true,'seed',$4::text,'ordinal',i),
       'knowledge',encode(digest(($4::text || ':' || i::text),'sha256'),'hex'),
       64,'[]'::jsonb
       from generate_series($5::int,$6::int) as generated(i)`,
    [
      fixture.spaceId,
      fixture.vaultId,
      fixture.externalPrefix,
      fixture.runId,
      start,
      end,
    ],
  );
  return elapsedMs;
}

async function insertUnits(
  fixture: FixtureIds,
  start: number,
  end: number,
): Promise<number> {
  if (start > end) return 0;
  const { elapsedMs } = await timedQuery(
    `insert into knowledge_units(
       document_id,space_id,vault_id,unit_key,unit_type,heading_path,body,
       content_hash,corpus_revision,lifecycle,trust_tier,source_ids,token_estimate,
       parent_unit_id,document_revision,permissions,locator,artifact_id,
       structural_order,container_only,embedding_eligible
     )
     select
       d.id,d.space_id,d.vault_id,'root','PARAGRAPH',array['Synthetic']::text[],
       format('Synthetic architecture unit %s for seed %s.',i,$4::text),
       encode(digest(($4::text || ':unit:' || i::text),'sha256'),'hex'),
       'synthetic-v1','ACTIVE','VERIFIED','{}'::text[],64,null,'synthetic-v1',
       '{}'::jsonb,jsonb_build_object('path',d.path),null,0,false,false
       from generate_series($5::int,$6::int) as generated(i)
       join knowledge_documents d
         on d.space_id=$1 and d.vault_id=$2 and d.external_id=$3 || i::text`,
    [
      fixture.spaceId,
      fixture.vaultId,
      fixture.externalPrefix,
      fixture.runId,
      start,
      end,
    ],
  );
  return elapsedMs;
}

async function insertEmbeddings(
  fixture: FixtureIds,
  start: number,
  end: number,
): Promise<number> {
  if (start > end) return 0;
  const { elapsedMs } = await timedQuery(
    `insert into unit_embeddings(unit_id,generation_id,content_hash,embedding)
     select
       u.id,$4,
       encode(digest(($5::text || ':embedding:' || i::text),'sha256'),'hex'),
       ('[' || (((i % 1000)::numeric / 1000)::text) || ',' ||
         repeat('0.01,',62) || '0.01]')::vector(64)
       from generate_series($6::int,$7::int) as generated(i)
       join knowledge_documents d
         on d.space_id=$1 and d.vault_id=$2 and d.external_id=$3 || i::text
       join knowledge_units u
         on u.document_id=d.id and u.space_id=$1 and u.vault_id=$2
      on conflict (unit_id,generation_id) do nothing`,
    [
      fixture.spaceId,
      fixture.vaultId,
      fixture.externalPrefix,
      fixture.embeddingGenerationId,
      fixture.runId,
      start,
      end,
    ],
  );
  return elapsedMs;
}

async function insertRelations(
  fixture: FixtureIds,
  start: number,
  end: number,
): Promise<number> {
  if (start > end) return 0;
  const { elapsedMs } = await timedQuery(
    `insert into knowledge_relations(
       space_id,from_document_id,to_document_id,relation_type,weight,provenance,metadata
     )
     select $1,from_document.id,to_document.id,'supports',1.0,'synthetic-load-scale',
            jsonb_build_object('seed',$4::text,'ordinal',i)
       from generate_series($5::int,$6::int) as generated(i)
       join knowledge_documents from_document
         on from_document.vault_id=$2
        and from_document.external_id=$3 || i::text
       join knowledge_documents to_document
         on to_document.vault_id=$2
        and to_document.external_id=$3 || (i + 1)::text
      on conflict (from_document_id,to_document_id,relation_type,provenance) do nothing`,
    [
      fixture.spaceId,
      fixture.vaultId,
      fixture.externalPrefix,
      fixture.runId,
      start,
      end,
    ],
  );
  return elapsedMs;
}

function deterministicUuid(seed: string, ordinal: number): string {
  const hex = createHash("sha256")
    .update(`${seed}:${ordinal}`)
    .digest("hex")
    .slice(0, 32);
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

function syntheticPacketCandidates(
  fixture: FixtureIds,
  target: number,
  seed: string,
): PacketCandidate[] {
  const candidates: PacketCandidate[] = [];
  for (let ordinal = 1; ordinal <= target; ordinal += 1) {
    const documentId = deterministicUuid(`${fixture.runId}:${seed}`, ordinal);
    const unitId = deterministicUuid(`${fixture.runId}:${seed}:unit`, ordinal);
    const content = `Synthetic architecture context candidate ${ordinal} for scale seed ${seed}.`;
    const hit: SearchHit = {
      documentId,
      vaultId: fixture.vaultId,
      unitId,
      unitType: "PARAGRAPH",
      revision: "synthetic-v1",
      title: `Synthetic architecture document ${ordinal}`,
      type: "synthetic-document",
      trust: "MACHINE_SUPPORTED",
      lifecycle: "ACTIVE",
      score: 1 / ordinal,
      reasons: ["lexical"],
      excerpt: content,
      citations: [],
    };
    candidates.push({ hit, content, kind: "concept" });
  }
  return candidates;
}

function measureContextPacket(
  fixture: FixtureIds,
  target: number,
  seed: string,
  iterations: number,
): ContextPacketMeasurement {
  if (typeof global.gc === "function") global.gc();
  const memoryBefore = snapshotMemory();
  const candidateStarted = performance.now();
  const candidates = syntheticPacketCandidates(fixture, target, seed);
  const candidateGenerationMs = performance.now() - candidateStarted;
  const request: SearchRequest = {
    query: "architecture synthetic",
    spaceId: fixture.spaceId,
    vaultId: fixture.vaultId,
    vaultIds: [fixture.vaultId],
    federated: false,
    types: [],
    minimumTrust: "MACHINE_SUPPORTED",
    mode: "SOURCE_BACKED",
    limit: 20,
  };
  const build = () =>
    buildContextPacket({
      request,
      intent: "GLOBAL_SYNTHESIS",
      corpusRevision: "synthetic-v1",
      maxTokens: 12_000,
      maxSectionsPerDocument: 1,
      candidates,
      retrievalConfiguration: {
        version: "synthetic-scale-v1",
        channels: ["lexical"],
        vectorEnabled: false,
      },
    });
  let packet = build();
  const samples: number[] = [];
  for (let iteration = 0; iteration < iterations; iteration += 1) {
    const started = performance.now();
    packet = build();
    samples.push(performance.now() - started);
  }
  const memoryAfter = snapshotMemory();
  return {
    candidateCount: candidates.length,
    candidateGenerationMs: roundMs(candidateGenerationMs),
    latency: summarize(samples),
    selectedSections: packet.sections.length,
    omittedCandidates: candidates.length - packet.sections.length,
    usedTokens: packet.budget.usedTokens,
    status: packet.status,
    memoryBefore,
    memoryAfter,
    rssDeltaBytes: memoryAfter.rssBytes - memoryBefore.rssBytes,
    heapDeltaBytes: memoryAfter.heapUsedBytes - memoryBefore.heapUsedBytes,
  };
}

async function loadToTarget(
  fixture: FixtureIds,
  previousTarget: number,
  target: number,
): Promise<ScaleResult["loadLatencyMs"]> {
  const started = performance.now();
  await client.query("begin");
  let documentsInsert = 0;
  let unitsInsert = 0;
  let embeddingsInsert = 0;
  let relationsInsert = 0;
  let commit = 0;
  try {
    const start = previousTarget + 1;
    try {
      documentsInsert = await insertDocuments(fixture, start, target);
    } catch (error) {
      throw new Error(`document insert failed: ${errorMessage(error)}`);
    }
    try {
      unitsInsert = await insertUnits(fixture, start, target);
    } catch (error) {
      throw new Error(`unit insert failed: ${errorMessage(error)}`);
    }
    try {
      embeddingsInsert = await insertEmbeddings(fixture, start, target);
    } catch (error) {
      throw new Error(`embedding insert failed: ${errorMessage(error)}`);
    }
    const relationStart = previousTarget === 0 ? 1 : previousTarget;
    try {
      relationsInsert = await insertRelations(
        fixture,
        relationStart,
        target - 1,
      );
    } catch (error) {
      throw new Error(`relation insert failed: ${errorMessage(error)}`);
    }
    const commitStarted = performance.now();
    await client.query("commit");
    commit = performance.now() - commitStarted;
  } catch (error) {
    await client.query("rollback");
    throw error;
  }
  const analyzeStarted = performance.now();
  await client.query(
    "analyze knowledge_documents, knowledge_units, knowledge_relations",
  );
  const analyze = performance.now() - analyzeStarted;
  return {
    documentsInsert: roundMs(documentsInsert),
    unitsInsert: roundMs(unitsInsert),
    embeddingsInsert: roundMs(embeddingsInsert),
    relationsInsert: roundMs(relationsInsert),
    commit: roundMs(commit),
    analyze: roundMs(analyze),
    total: roundMs(performance.now() - started),
  };
}

async function measureQueries(
  fixture: FixtureIds,
  target: number,
  iterations: number,
): Promise<QueryMeasurement[]> {
  const documentPath = `synthetic/${target}.md`;
  const graphProbePath = `synthetic/${Math.max(1, target - 1)}.md`;
  const vectorProbe = `[${((target % 1000) / 1000).toFixed(3)},${"0.01,".repeat(62)}0.01]`;
  const operations: Array<{
    name: string;
    description: string;
    run: () => Promise<number>;
  }> = [
    {
      name: "point-document-by-vault-path",
      description: "Indexed point lookup by vault and path.",
      run: async () => {
        const { result } = await timedQuery(
          `select id,title from knowledge_documents
             where vault_id=$1 and path=$2 limit 1`,
          [fixture.vaultId, documentPath],
        );
        return result.rowCount ?? 0;
      },
    },
    {
      name: "lexical-document-search",
      description: "GIN-backed full-text search over the synthetic vault.",
      run: async () => {
        const { result } = await timedQuery(
          `select id,ts_rank(search_vector,plainto_tsquery('simple',$2)) as rank
             from knowledge_documents
            where vault_id=$1
              and search_vector @@ plainto_tsquery('simple',$2)
            order by rank desc,id
            limit 20`,
          [fixture.vaultId, "architecture synthetic"],
        );
        return result.rowCount ?? 0;
      },
    },
    {
      name: "graph-neighbor-lookup",
      description:
        "Indexed outgoing relation lookup for a document in the synthetic chain.",
      run: async () => {
        const { result } = await timedQuery<{ count: Numeric }>(
          `select count(*)::int as count
             from knowledge_relations r
            where r.space_id=$1
              and r.from_document_id=(
                select id from knowledge_documents
                 where vault_id=$2 and path=$3 limit 1
              )`,
          [fixture.spaceId, fixture.vaultId, graphProbePath],
        );
        return asNumber(result.rows[0]?.count);
      },
    },
    {
      name: "unit-by-document-lookup",
      description:
        "Structural unit lookup joined through an indexed document identity.",
      run: async () => {
        const { result } = await timedQuery(
          `select u.id,u.unit_key
             from knowledge_units u
             join knowledge_documents d on d.id=u.document_id
            where u.vault_id=$1 and d.path=$2 limit 1`,
          [fixture.vaultId, documentPath],
        );
        return result.rowCount ?? 0;
      },
    },
    {
      name: "synthetic-vector-unit-search",
      description:
        "pgvector nearest-neighbor query over fixed 64-dimensional synthetic vectors; not semantic quality evidence.",
      run: async () => {
        const { result } = await timedQuery(
          `select e.unit_id,e.embedding <=> $3::vector as distance
             from unit_embeddings e
             join knowledge_units u on u.id=e.unit_id and u.vault_id=$2
            where e.generation_id=$1
            order by e.embedding <=> $3::vector
            limit 20`,
          [fixture.embeddingGenerationId, fixture.vaultId, vectorProbe],
        );
        return result.rowCount ?? 0;
      },
    },
    {
      name: "vault-document-count",
      description: "Count over the vault scope to expose aggregate growth.",
      run: async () => {
        const { result } = await timedQuery<{ count: Numeric }>(
          "select count(*)::bigint as count from knowledge_documents where vault_id=$1",
          [fixture.vaultId],
        );
        return asNumber(result.rows[0]?.count);
      },
    },
  ];

  const measurements: QueryMeasurement[] = [];
  for (const operation of operations) {
    await operation.run();
    const samples: number[] = [];
    const observedRowCounts: number[] = [];
    for (let iteration = 0; iteration < iterations; iteration += 1) {
      const started = performance.now();
      const rowCount = await operation.run();
      samples.push(performance.now() - started);
      observedRowCounts.push(rowCount);
    }
    measurements.push({
      name: operation.name,
      description: operation.description,
      stats: summarize(samples),
      observedRowCounts,
    });
  }
  return measurements;
}

async function cleanupFixture(fixture: FixtureIds): Promise<CleanupResult> {
  const cleanupIndex = "akp_scale_benchmark_cleanup_invalidated_by_idx";
  let cleanupIndexCreated = false;
  try {
    const existingIndex = await client.query<{ present: boolean }>(
      "select to_regclass($1)::text is not null as present",
      [`public.${cleanupIndex}`],
    );
    if (!existingIndex.rows[0]?.present) {
      // The legacy self-FK on knowledge_documents has no supporting index.
      // Without this disposable cleanup index, deleting a large fixture makes
      // PostgreSQL rescan the document table once per row (O(n^2)).
      await client.query(
        `create index ${cleanupIndex} on knowledge_documents(invalidated_by)`,
      );
      cleanupIndexCreated = true;
    }
    await client.query("begin");
    await client.query("delete from knowledge_lint_runs where vault_id=$1", [
      fixture.vaultId,
    ]);
    await client.query("delete from error_book where vault_id=$1", [
      fixture.vaultId,
    ]);
    await client.query("delete from schema_dry_runs where vault_id=$1", [
      fixture.vaultId,
    ]);
    await client.query("delete from audit_events where vault_id=$1", [
      fixture.vaultId,
    ]);
    await client.query("delete from context_packets where vault_id=$1", [
      fixture.vaultId,
    ]);
    await client.query("delete from document_leases where vault_id=$1", [
      fixture.vaultId,
    ]);
    await client.query("delete from agent_sessions where vault_id=$1", [
      fixture.vaultId,
    ]);
    await client.query("delete from projects where vault_id=$1", [
      fixture.vaultId,
    ]);
    await client.query("delete from eval_cases where vault_id=$1", [
      fixture.vaultId,
    ]);
    await client.query("delete from eval_runs where vault_id=$1", [
      fixture.vaultId,
    ]);
    await client.query("delete from reviews where vault_id=$1", [
      fixture.vaultId,
    ]);
    await client.query("delete from ingest_jobs where vault_id=$1", [
      fixture.vaultId,
    ]);
    await client.query("delete from evidence where vault_id=$1", [
      fixture.vaultId,
    ]);
    await client.query("delete from sources where vault_id=$1", [
      fixture.vaultId,
    ]);
    await client.query("delete from embedding_generations where vault_id=$1", [
      fixture.vaultId,
    ]);
    await client.query("delete from knowledge_relations where space_id=$1", [
      fixture.spaceId,
    ]);
    await client.query("delete from knowledge_units where space_id=$1", [
      fixture.spaceId,
    ]);
    await client.query("delete from knowledge_documents where space_id=$1", [
      fixture.spaceId,
    ]);
    await client.query("delete from vault_index_revisions where space_id=$1", [
      fixture.spaceId,
    ]);
    await client.query("delete from vault_memberships where vault_id=$1", [
      fixture.vaultId,
    ]);
    await client.query("delete from vaults where id=$1", [fixture.vaultId]);
    await client.query("delete from memberships where space_id=$1", [
      fixture.spaceId,
    ]);
    await client.query("delete from spaces where id=$1", [fixture.spaceId]);
    await client.query("delete from organizations where id=$1", [
      fixture.organizationId,
    ]);
    await client.query("commit");
    const remaining = await fixtureCounts(fixture);
    if (cleanupIndexCreated) {
      await client.query(`drop index if exists ${cleanupIndex}`);
      cleanupIndexCreated = false;
    }
    return {
      attempted: true,
      succeeded:
        remaining.documents === 0 &&
        remaining.units === 0 &&
        remaining.relations === 0 &&
        remaining.embeddings === 0,
      remainingRows: remaining,
    };
  } catch (error) {
    try {
      await client.query("rollback");
    } catch {
      // Preserve the original cleanup error in the report.
    }
    if (cleanupIndexCreated) {
      try {
        await client.query(`drop index if exists ${cleanupIndex}`);
      } catch {
        // The connection can be gone after a database restart; preserve the
        // cleanup failure and let the caller report it.
      }
    }
    return {
      attempted: true,
      succeeded: false,
      remainingRows: null,
      error: errorMessage(error),
    };
  }
}

function buildGrowth(results: ScaleResult[]): ScaleReport["growth"] {
  if (results.length === 0) {
    return {
      firstTarget: null,
      lastTarget: null,
      documentGrowthFactor: null,
      storageGrowthBytes: null,
      queryP95ByTarget: {},
    };
  }
  const first = results[0];
  const last = results[results.length - 1];
  if (first === undefined || last === undefined) {
    throw new Error("growth requires at least one scale result");
  }
  const queryP95ByTarget: Record<string, Record<string, number>> = {};
  for (const result of results) {
    queryP95ByTarget[String(result.targetDocuments)] = Object.fromEntries(
      result.queryLatency.map((measurement) => [
        measurement.name,
        measurement.stats.p95Ms,
      ]),
    );
  }
  return {
    firstTarget: first.targetDocuments,
    lastTarget: last.targetDocuments,
    documentGrowthFactor:
      first.rows.documents === 0
        ? null
        : roundMs(last.rows.documents / first.rows.documents),
    storageGrowthBytes:
      last.storage.afterLoad.databaseBytes -
      first.storage.beforeLoad.databaseBytes,
    queryP95ByTarget,
  };
}

async function runBenchmark(
  targets: number[],
  iterations: number,
  seed: string,
): Promise<ScaleReport> {
  await client.connect();
  const info = await databaseInfo();
  const fixture = await createFixture(seed);
  let cleanup: CleanupResult = {
    attempted: false,
    succeeded: false,
    remainingRows: null,
  };
  const results: ScaleResult[] = [];
  let baselineStorage = await storageSnapshot();
  let previousStorage = baselineStorage;
  let previousTarget = 0;
  let failure: string | undefined;
  try {
    for (const target of targets) {
      const beforeLoad = snapshotMemory();
      const storageBefore = await storageSnapshot();
      const loadLatencyMs = await loadToTarget(fixture, previousTarget, target);
      const afterLoad = snapshotMemory();
      const storageAfter = await storageSnapshot();
      const rows = await fixtureCounts(fixture);
      const queryLatency = await measureQueries(fixture, target, iterations);
      const afterQueries = snapshotMemory();
      const contextPacket = measureContextPacket(
        fixture,
        target,
        seed,
        iterations,
      );
      const afterContextPacket = contextPacket.memoryAfter;
      const loadMemoryDelta = subtractMemory(afterLoad, beforeLoad);
      const queryMemoryDelta = subtractMemory(afterQueries, afterLoad);
      results.push({
        targetDocuments: target,
        appendedDocuments: target - previousTarget,
        appendedRelations:
          Math.max(0, target - 1) - Math.max(0, previousTarget - 1),
        appendedEmbeddings: target - previousTarget,
        rows,
        loadLatencyMs,
        queryLatency,
        memory: {
          gcAvailable: typeof global.gc === "function",
          beforeLoad,
          afterLoad,
          afterQueries,
          afterContextPacket,
          loadRssDeltaBytes: loadMemoryDelta.rssBytes,
          queryRssDeltaBytes: queryMemoryDelta.rssBytes,
          loadHeapDeltaBytes: loadMemoryDelta.heapUsedBytes,
          queryHeapDeltaBytes: queryMemoryDelta.heapUsedBytes,
          contextPacketRssDeltaBytes: contextPacket.rssDeltaBytes,
          contextPacketHeapDeltaBytes: contextPacket.heapDeltaBytes,
        },
        storage: {
          beforeLoad: storageBefore,
          afterLoad: storageAfter,
          deltaFromBaseline: subtractStorage(storageAfter, baselineStorage),
          deltaFromPreviousTarget: subtractStorage(
            storageAfter,
            previousStorage,
          ),
        },
        contextPacket,
      });
      previousTarget = target;
      previousStorage = storageAfter;
    }
  } catch (error) {
    failure = errorMessage(error);
  } finally {
    cleanup = await cleanupFixture(fixture);
  }
  const targetRowsExact = results.every(
    (result) =>
      result.rows.documents === result.targetDocuments &&
      result.rows.units === result.targetDocuments &&
      result.rows.embeddings === result.targetDocuments,
  );
  const relationRowsExact = results.every(
    (result) =>
      result.rows.relations === Math.max(0, result.targetDocuments - 1),
  );
  const report: ScaleReport = {
    schemaVersion: "akp.scale-benchmark.v1",
    generatedAt: new Date().toISOString(),
    status:
      failure || !cleanup.succeeded || !targetRowsExact || !relationRowsExact
        ? "FAILED"
        : "PASSED",
    evidenceLevel: "SYNTHETIC_ISOLATED_POSTGRES",
    coverageStatus: "PARTIAL",
    execution: {
      nodeVersion: process.version,
      platform: process.platform,
      postgresVersion: info.version,
      databaseName: info.name,
      seed,
      targets,
      iterations,
      queryLatencyClock:
        "Node performance.now around client.query; includes client/network/PostgreSQL time",
      fixtureGeneration:
        "PostgreSQL generate_series with deterministic seed/content; no real vault data",
    },
    acceptance: {
      targetRowsExact,
      relationRowsExact,
      fixtureScoped: true,
      cleanupSucceeded: cleanup.succeeded,
    },
    results,
    growth: buildGrowth(results),
    measured: [
      "PostgreSQL synthetic document/unit/relation materialisation latency",
      "Client-observed point, lexical, synthetic pgvector, graph, unit and count query latency",
      "Deterministic context-packet assembly latency for candidate sets sized to each target",
      "Node process RSS and heap deltas around load and query phases",
      "PostgreSQL database and table relation storage growth",
      "Exact row-count and fixture cleanup acceptance checks",
    ],
    notMeasured: [
      {
        dimension: "real vault corpus",
        reason:
          "The fixture is generated and isolated; no private or external vault was read.",
      },
      {
        dimension: "semantic vector quality or real embedding generation",
        reason:
          "The vector path uses deterministic fixed 64-dimensional fixture values; no provider, model quality or relevance ground truth was evaluated.",
      },
      {
        dimension: "HTTP/API and worker throughput",
        reason:
          "The harness calls PostgreSQL and the packet builder directly; it does not claim service-level throughput or concurrency results.",
      },
      {
        dimension: "context packet retrieval/persistence path",
        reason:
          "Only the deterministic in-process packet builder is measured; candidate retrieval, API serialization and context_packets persistence are not measured.",
      },
      {
        dimension: "incremental indexing and event delivery",
        reason:
          "No outbox event, worker, or incremental-index run was created; rebuild/reuse behavior remains unmeasured.",
      },
      {
        dimension: "PostgreSQL server RAM",
        reason:
          "Only the benchmark Node process memory is observable without a server-side memory extension or host telemetry.",
      },
      {
        dimension: "multi-tenant concurrent isolation under load",
        reason:
          "The fixture uses one isolated vault and sequential operations; concurrency and cross-tenant contention were not exercised.",
      },
    ],
    limitations: [
      "Storage snapshots use whole-database and whole-table relation sizes, so they include pre-existing isolated-database overhead and index pages.",
      "The cumulative targets append rows to one fixture; they are not independent cold-start trials and cache state may affect latency.",
      "Vector timings exercise pgvector operators/indexes over deterministic coordinates, not embedding-model quality or semantic recall.",
      "Context-packet timings exercise the in-process deterministic builder over synthetic candidates, not retrieval, persistence or API latency.",
      "The reported memory is Node RSS/heap, not PostgreSQL backend or container memory.",
      "A passing result is evidence for this synthetic PostgreSQL path only; it is not a production capacity SLO or a vector-quality claim.",
    ],
    cleanup,
    ...(failure === undefined ? {} : { failure }),
  };
  await client.end();
  return report;
}

async function main(): Promise<void> {
  const argv = process.argv.slice(2);
  if (argv.includes("--help")) {
    printUsage();
    return;
  }
  if (!process.env.DATABASE_URL) {
    throw new Error(
      "DATABASE_URL is required and must point to an isolated disposable database",
    );
  }
  const repositoryRoot = path.resolve(
    argValue(argv, "--repo-root") ?? process.cwd(),
  );
  const output = path.resolve(
    repositoryRoot,
    argValue(argv, "--output") ?? "reports/scale/load-scale-benchmark.json",
  );
  const targets = parseTargets(argValue(argv, "--targets"));
  const iterations = parsePositiveInteger(
    argValue(argv, "--iterations") ?? "5",
    "iterations",
  );
  if (iterations > 50)
    throw new Error("iterations above 50 are refused by the harness");
  const seed = argValue(argv, "--seed") ?? "akp-scale-v1";
  const report = await runBenchmark(targets, iterations, seed);
  if (!argv.includes("--stdout")) {
    await mkdir(path.dirname(output), { recursive: true });
    await writeFile(output, `${JSON.stringify(report, null, 2)}\n`, "utf8");
  }
  process.stdout.write(
    `${JSON.stringify(
      argv.includes("--stdout")
        ? report
        : {
            status: report.status,
            evidenceLevel: report.evidenceLevel,
            targets: report.execution.targets,
            iterations: report.execution.iterations,
            output: path.relative(repositoryRoot, output),
            cleanup: report.cleanup.succeeded,
          },
    )}\n`,
  );
  if (report.status === "FAILED") process.exitCode = 1;
}

try {
  await main();
} catch (error) {
  process.stderr.write(
    `${error instanceof Error ? (error.stack ?? error.message) : String(error)}\n`,
  );
  process.exitCode = 1;
}
