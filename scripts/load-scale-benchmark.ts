/**
 * Reproducible synthetic PostgreSQL load/scale benchmark.
 *
 * This harness deliberately measures only the dimensions it can observe in an
 * isolated database: server-side fixture materialisation, lexical/graph and
 * synthetic pgvector query latency, deterministic context-packet assembly,
 * the Node process RSS/heap, and PostgreSQL relation/database storage. It does
 * not claim evidence about a real vault, semantic vector quality, HTTP/API or
 * worker throughput, or the full incremental-indexing pipeline. Those limits
 * are emitted explicitly in `notMeasured`/`limitations`.
 *
 * The fixture is created in a fresh organization/space/vault and is removed in
 * a finally block. Data is generated by PostgreSQL's generate_series, so the
 * harness does not materialise 100K rows in the Node process.
 */
